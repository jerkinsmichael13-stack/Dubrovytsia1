import re
def norm(s):
    # населені пункти
    s=s.replace('Сельців','Сельця').replace('Сельцях','Сельці')
    s=re.sub(r'(?<![ВвУу] )(?<![ВвУу]\xa0)Сельці\b','Селець',s)
    s=re.sub(r'\bСельце\b','Селець',s).replace('Сільце','Селець')
    s=s.replace('Острівська','Острівців').replace('Острівськ','Острівці')
    # прізвища та імена
    s=s.replace('Ізаак','Ісаак')
    s=re.sub(r'Буков(?=ець|ця|цю|цем|ці|ців)','Боков',s)
    s=re.sub(r'П[еи]р[іи]шк','Пирішк',s)
    s=s.replace('Лятт','Латт')
    s=re.sub(r'Сибиковськ(?![а-я]* \(кирилицею\))','Сибіковськ',s)
    for a,b in [('Іполит','Іполіт'),('Жижновськ','Жизновськ'),('Алексієвич','Олексієвець'),('Олехнієвича','Олексієвця'),('Олехнієвичу','Олексієвцю'),('Олехнієвич','Олексієвець'),('Дембковськ','Димковськ'),('Кузьміном','Кузином'),('Кузьмінові','Кузинові'),('Кузьміну','Кузину'),('Кузьміна','Кузина'),('Кузьмін','Кузин'),('Валковц','Вальковц'),('Валковець','Вальковець'),
                ('Вєвюровськ',"Вев'юровськ"),('Вєвьоровськ',"Вев'юровськ"),('Галіцьк','Галицьк'),('Зєлінськ','Зелінськ'),
                ('Юзеф Зелеський','Юзеф Залевський'),('Юзефом Дзелецьким','Юзефом Залевським'),('Клуйко','Клюйко'),
                ('Малахія','Меланія'),('Мелахією','Меланією'),('Мелахії','Меланії'),('Мелахія','Меланія'),
                ('Пальоньк','Пальонк'),('Пирц-Хоїнськ','Пирц-Хойньськ'),('Пшедзімірськ','Пшедзимирськ'),('Радваньськ','Радванськ'),
                ('Старжевськ','Старчевськ'),('Улятовськ','Улатовськ'),('Цихого','Ціхого'),('Ядвіґ','Ядвіг'),
                ('Зигмунта Грекка','Зигмунта Ґрекка'),('Зигмунт Грекк','Зигмунт Ґрекк'),('пана Грека','пана Ґрекка')]:
        s=s.replace(a,b)
    s=re.sub(r'Ґрек(?!к)(?= \(Grekk\)| і Шуйкевич)','Ґрекк',s)
    s=re.sub(r'Зигмунт Ґрек(?!к)','Зигмунт Ґрекк',s)
    return s
def norm_docs(s):
    s=norm(s)
    s=re.sub(r'(?<!станції )(?<!ст\. )Домбровиц','Дубровиц',s)
    return s
